export function TabBar() {
  const current = tab.value
  return (
    <nav class="tabbar" aria-label="Sections">
      {TABS.map((t) => (
        <button
          key={t.id}
          class={`tab${current === t.id ? ' on' : ''}`}
          aria-current={current === t.id ? 'page' : undefined}
          onClick={() => (tab.value = t.id)}
        >
          {t.icon}
          <span>{t.label}</span>
        </button>
      ))}
    </nav>
  )
}
